import type { Metadata } from "next";
import { SITE, absoluteUrl } from "@/config/site";

/** Schema.org node ids, so pages can point at the one Organization / WebSite instead of repeating them. */
export const ORGANIZATION_ID = absoluteUrl("/#organization");
export const WEBSITE_ID = absoluteUrl("/#website");

/** The brand, as structured data: gives search results the right name and logo. */
export const organizationJsonLd = {
  "@type": "Organization",
  "@id": ORGANIZATION_ID,
  name: SITE.name,
  url: absoluteUrl("/"),
  logo: { "@type": "ImageObject", url: absoluteUrl(SITE.logo), width: 512, height: 512 },
};

export const websiteJsonLd = {
  "@type": "WebSite",
  "@id": WEBSITE_ID,
  name: SITE.name,
  url: absoluteUrl("/"),
  description: SITE.description,
  inLanguage: "en-IN",
  publisher: { "@id": ORGANIZATION_ID },
};

/** The share image generated by app/opengraph-image.tsx. */
const SHARE_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: `${SITE.name} — petty cash, in control.` };

/**
 * Metadata for a public page. Child segments replace `openGraph` and `twitter` wholesale
 * (metadata merges shallowly), which also drops the root's generated image, so every field
 * the root sets is repeated here.
 *
 * `ownImage`: the segment has its own opengraph-image file, so leave `images` out; Next fills
 * og:image from the file and twitter:image inherits it.
 */
export function pageMetadata({
  title,
  description,
  path,
  ownImage = false,
}: {
  title: string;
  description: string;
  path: string;
  ownImage?: boolean;
}): Metadata {
  const shareTitle = `${title} · ${SITE.name}`;
  const images = ownImage ? {} : { images: [SHARE_IMAGE] };
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: { type: "website", siteName: SITE.name, locale: "en_IN", url: path, title: shareTitle, description, ...images },
    twitter: { card: "summary_large_image", title: shareTitle, description, ...images },
  };
}
